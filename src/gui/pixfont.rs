fn table() -> &'static [[u8; 8]; 96] {
    static T: OnceLock<[[u8; 8]; 96]> = OnceLock::new();
    T.get_or_init(|| {
        let mut t = [[0xffu8; 8]; 96];
        for (c, s) in GLYPHS {
            if s.len() != 64 {
                continue;
            }
            let i = *c as usize - 0x20;
            for (row, chunk) in s.as_bytes().chunks(8).enumerate() {
                let mut bits = 0u8;
                for (col, b) in chunk.iter().enumerate() {
                    if *b == b'#' {
                        bits |= 0x80 >> col;
                    }
                }
                t[i][row] = bits;
            }
        }
        t
    })
}

/// The rows of a character (bit 7 is the left column).
pub fn glyph(c: char) -> [u8; 8] {
    let c = c.to_ascii_uppercase();
    let i = c as u32;
    if (0x20..0x80).contains(&i) {
        let g = table()[(i - 0x20) as usize];
        if g != [0xff; 8] {
            return g;
        }
    }
    // A block for anything else, like the C64's reverse space.
    [0, 0x7e, 0x7e, 0x7e, 0x7e, 0x7e, 0x7e, 0]
}

/// True when every character has its own glyph.
pub fn covers(s: &str) -> bool {
    s.chars().all(|c| {
        let i = c.to_ascii_uppercase() as u32;
        (0x20..0x80).contains(&i) && table()[(i - 0x20) as usize] != [0xff; 8]
    })
}

pub fn width(s: &str, scale: i32) -> i32 {
    s.chars().count() as i32 * 8 * scale
}

/// Draw `s` at (x, y), each pixel `scale` square. Returns the width.
pub fn draw(cv: &mut Canvas, x: i32, y: i32, s: &str, scale: i32, color: u32) -> i32 {
    let mut gx = x;
    for c in s.chars() {
        let g = glyph(c);
        for (row, bits) in g.iter().enumerate() {
            if *bits == 0 {
                continue;
            }
            // Runs of set bits as one fill each.
            let mut col = 0;
            while col < 8 {
                if bits & (0x80 >> col) != 0 {
                    let start = col;
                    while col < 8 && bits & (0x80 >> col) != 0 {
                        col += 1;
                    }
                    cv.fill(
                        Rect::new(
                            gx + start * scale,
                            y + row as i32 * scale,
                            (col - start) * scale,
                            scale,
                        ),
                        color,
                    );
                } else {
                    col += 1;
                }
            }
        }
        gx += 8 * scale;
    }
    gx - x
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_8x8_and_letters_exist() {
        for (c, s) in GLYPHS {
            assert!(
                s.is_empty() || s.len() == 64,
                "glyph {c:?} has {} cells",
                s.len()
            );
        }
        assert!(covers("NIRUSID 0.1.0: C-4 PUL+TRI 50% [A]"));
        assert!(covers("lower case too"));
        assert!(!covers("Söder"));
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph(' '), [0; 8]);
        // The A has its two-pixel legs on rows 2..=6.
        assert_eq!(glyph('A')[3], 0b0111_1110);
        let mut cv = Canvas::new(32, 8);
        assert_eq!(draw(&mut cv, 0, 0, "HI", 1, 0xffffff), 16);
        assert_eq!(cv.get(1, 0), 0xffffff);
    }
}
